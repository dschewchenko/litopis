export function resolveDatePickerMessages(
  locale: string | undefined,
  overrides: DatePickerMessageOverrides | undefined,
): DatePickerMessages {
  const resolvedLocale = resolveLocale(locale);
  const language = resolvedLocale.toLowerCase().split("-")[0]!;
  const defaults = DATE_PICKER_MESSAGES[language] ?? DATE_PICKER_MESSAGES.en!;

  return {
    clear: resolveValue(overrides?.clear, defaults.clear),
    chooseMonth: resolveValue(overrides?.chooseMonth, defaults.chooseMonth),
    chooseMonthAndYear: resolveValue(overrides?.chooseMonthAndYear, defaults.chooseMonthAndYear),
    chooseYear: resolveValue(overrides?.chooseYear, defaults.chooseYear),
    currentYearPage: resolveValue(overrides?.currentYearPage, defaults.currentYearPage),
    date: resolveValue(overrides?.date, defaults.date),
    dateOnOrAfter: resolveValue(overrides?.dateOnOrAfter, defaults.dateOnOrAfter),
    dateOnOrBefore: resolveValue(overrides?.dateOnOrBefore, defaults.dateOnOrBefore),
    end: resolveValue(overrides?.end, defaults.end),
    enterValidDate: resolveValue(overrides?.enterValidDate, defaults.enterValidDate),
    nextMonth: resolveValue(overrides?.nextMonth, defaults.nextMonth),
    nextYear: resolveValue(overrides?.nextYear, defaults.nextYear),
    nextYears: resolveValue(overrides?.nextYears, defaults.nextYears),
    previousMonth: resolveValue(overrides?.previousMonth, defaults.previousMonth),
    previousYear: resolveValue(overrides?.previousYear, defaults.previousYear),
    previousYears: resolveValue(overrides?.previousYears, defaults.previousYears),
    seasons: {
      autumn: resolveValue(overrides?.seasons?.autumn, defaults.seasons.autumn),
      spring: resolveValue(overrides?.seasons?.spring, defaults.seasons.spring),
      summer: resolveValue(overrides?.seasons?.summer, defaults.seasons.summer),
      winter: resolveValue(overrides?.seasons?.winter, defaults.seasons.winter),
    },
    start: resolveValue(overrides?.start, defaults.start),
    today: resolveValue(overrides?.today, defaults.today),
  };
}

function resolveValue<T>(override: T | undefined, fallback: T): T {
  return override ?? fallback;
}
